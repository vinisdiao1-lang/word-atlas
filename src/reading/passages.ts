import type { ReadingPassage, ReadingQuestion } from "./types";

type Question = Omit<ReadingQuestion, "id">;
const tf = (
  prompt: string,
  answer: string,
  paragraph: number,
  evidence: string,
  explanation: string,
): Question => ({
  type: "tfng",
  prompt,
  answer,
  paragraph,
  evidence,
  explanation,
});
const mc = (
  prompt: string,
  options: string[],
  answer: string,
  paragraph: number,
  evidence: string,
  explanation: string,
): Question => ({
  type: "choice",
  prompt,
  options,
  answer,
  paragraph,
  evidence,
  explanation,
});
const gap = (
  prompt: string,
  answer: string,
  maxWords: number,
  paragraph: number,
  evidence: string,
  explanation: string,
): Question => ({
  type: "completion",
  prompt,
  answer,
  maxWords,
  paragraph,
  evidence,
  explanation,
});
const passage = (
  p: Omit<ReadingPassage, "questions"> & { questions: Question[] },
): ReadingPassage => ({
  ...p,
  questions: p.questions.map((q, i) => ({ ...q, id: `q${i + 1}` })),
});

